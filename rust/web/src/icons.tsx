// Icon set: Phosphor (regular weight) behind the `<Icon name size />` API the app already uses.
// `IconName` is a union of the keys below, so a name without an icon fails to compile.
import {
  ArrowClockwise,
  ArrowCounterClockwise,
  ArrowLineDown,
  ChartBar,
  Check,
  CircleHalf,
  CaretRight,
  ClockCounterClockwise,
  Columns,
  Command,
  Cube,
  Database,
  DownloadSimple,
  Eye,
  FloppyDisk,
  FolderOpen,
  Function as FunctionIcon,
  Funnel,
  Gear,
  Info,
  Keyboard,
  Lightning,
  Link,
  ListNumbers,
  MagnifyingGlass,
  Moon,
  Package,
  Play,
  Plugs,
  PlugsConnected,
  Plus,
  Rows,
  Stack,
  Stop,
  Sun,
  Table,
  TerminalWindow,
  TextAlignLeft,
  TreeStructure,
  WarningCircle,
  X,
  type IconProps,
  type Icon as PhosphorIcon,
} from "@phosphor-icons/react";

const ICONS = {
  // Toolbar actions (names the app already used)
  run: Play,
  stop: Stop,
  commit: Check,
  rollback: ArrowCounterClockwise,
  format: TextAlignLeft,
  history: ClockCounterClockwise,
  plan: TreeStructure,
  stats: ChartBar,
  export: DownloadSimple,
  save: FloppyDisk,
  open: FolderOpen,
  commands: Command,
  connect: PlugsConnected,
  disconnect: Plugs,
  refresh: ArrowClockwise,
  database: Database,
  search: MagnifyingGlass,
  table: Table,
  clear: X,
  close: X,
  update: ArrowLineDown,
  settings: Gear,
  // Workbench shell and object tree
  keyboard: Keyboard,
  package: Package,
  view: Eye,
  function: FunctionIcon,
  trigger: Lightning,
  sequence: ListNumbers,
  type: Cube,
  synonym: Link,
  procedure: TerminalWindow,
  schema: Stack,
  chevron: CaretRight,
  warning: WarningCircle,
  info: Info,
  plus: Plus,
  filter: Funnel,
  rows: Rows,
  columns: Columns,
  sun: Sun,
  moon: Moon,
  themeAuto: CircleHalf,
} as const satisfies Record<string, PhosphorIcon>;

export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 16,
  ...rest
}: { name: IconName; size?: number } & Omit<IconProps, "size" | "weight">) {
  const Glyph = ICONS[name];
  return <Glyph size={size} weight="regular" aria-hidden="true" {...rest} />;
}
